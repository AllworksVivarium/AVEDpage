import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes,randomUUID} from 'node:crypto';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve,sep} from 'node:path';
import {spawn} from 'node:child_process';
import {createServer} from 'node:net';
import {DatabaseSync} from 'node:sqlite';
import {MAX_GAME_STAKE,MAX_SHARED_GAME_STAKE,validateGameStake} from '../game-stake-limits.mjs';
import {cardStakes} from '../server-card-wallet.mjs';
import {defaultEconomy} from '../server-economy.mjs';

test('all fixed tickets and card reserves fit the common maximum',()=>{
 assert.equal(validateGameStake(100000),MAX_GAME_STAKE);
 assert.equal(validateGameStake(500000,MAX_SHARED_GAME_STAKE),500000);
 assert.throws(()=>validateGameStake(500001,MAX_SHARED_GAME_STAKE));
 for(const value of [100001,99,100.5,'100000',Infinity])assert.throws(()=>validateGameStake(value));
 assert.ok(defaultEconomy().scratch.every(t=>t.cost<=MAX_GAME_STAKE));
 assert.equal(cardStakes.reserve(cardStakes.max),MAX_GAME_STAKE);
});

test('HTTP rejects excess game stakes atomically, combines race markets, and allows larger stock orders',async t=>{
 const folder=mkdtempSync(join(tmpdir(),'aved-stake-cap-'));
 const password=randomBytes(24).toString('hex');
 const port=await new Promise(done=>{const socket=createServer();socket.listen(0,'127.0.0.1',()=>{const p=socket.address().port;socket.close(()=>done(p));});});
 const env={...process.env,DATA_DIR:folder,PORT:String(port),HOST:'127.0.0.1',NODE_ENV:'production',COOKIE_SECURE:'false',SESSION_SECRET:randomBytes(32).toString('hex'),BOOTSTRAP_ADMIN_USERNAME:'cap-admin',BOOTSTRAP_ADMIN_PASSWORD:password};
 const child=spawn(process.execPath,['server.mjs'],{cwd:new URL('../',import.meta.url),env,stdio:['ignore','pipe','pipe']});
 let errors='',db;child.stdout.resume();child.stderr.on('data',v=>errors+=v);
 t.after(async()=>{if(child.exitCode===null){const exit=new Promise(r=>child.once('exit',r));child.kill();await exit;}db?.close();assert.ok(resolve(folder).startsWith(resolve(tmpdir())+sep));rmSync(folder,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+port;
 let ready=false;for(let i=0;i<100;i++){try{if((await fetch(base+'/api/health')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,50));}assert.ok(ready,errors);
 const login=async identifier=>{const r=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({identifier,password})});assert.equal(r.status,200);return r.headers.get('set-cookie').split(';')[0];};
 const request=async(cookie,path,body)=>{const r=await fetch(base+path,{method:body?'POST':'GET',headers:{cookie,origin:base,'content-type':'application/json'},body:body?JSON.stringify(body):undefined});return{status:r.status,data:await r.json()};};
 const admin=await login('cap-admin');
 const created=await request(admin,'/api/admin/employees',{username:'cap-player',displayName:'限额测试员',password,initialBalance:10000000});assert.equal(created.status,201);
 const id=created.data.id,cookie=await login('cap-player'),call=(path,body)=>request(cookie,path,body);
 db=new DatabaseSync(join(folder,'wanyehui.db'),{readOnly:true});
 const balance=()=>db.prepare('SELECT SUM(delta) n FROM balance_ledger WHERE employee_id=?').get(id).n;
 const before=balance();
 for(const bet of [100001,100000.5,'100000'])assert.equal((await call('/api/player/games/slot',{bet,requestKey:randomUUID()})).status,400);
 assert.equal(balance(),before);assert.equal(db.prepare('SELECT COUNT(*) n FROM game_tickets WHERE employee_id=?').get(id).n,0);
 const spinKey=randomUUID();const spin=await call('/api/player/games/slot',{bet:100000,requestKey:spinKey});assert.equal(spin.status,200);
 const afterSpin=balance();assert.equal((await call('/api/player/games/slot',{bet:100000,requestKey:spinKey})).status,200);assert.equal(balance(),afterSpin);
 const flight=(await call('/api/player/games/sky/current')).data;
 assert.equal((await call('/api/player/games/sky/start',{round:flight.round,bet:500001})).status,400);assert.equal(balance(),afterSpin);
 assert.equal((await call('/api/player/games/sky/start',{round:flight.round,bet:500000})).status,200);assert.equal(balance(),afterSpin-500000);
 const race=(await call('/api/player/games/derby/current')).data;
 const bet={round:race.round,runner:0,market:'first',bet:300000};
 assert.equal((await call('/api/player/games/derby/bet',bet)).status,200);const afterFirst=balance();
 assert.equal((await call('/api/player/games/derby/bet',{...bet,market:'last',bet:200001})).status,400);assert.equal(balance(),afterFirst);
 const responses=await Promise.all([call('/api/player/games/derby/bet',{...bet,market:'last',bet:200000}),call('/api/player/games/derby/bet',{...bet,market:'last',bet:200000})]);
 assert.ok(responses.every(r=>r.status===200),JSON.stringify(responses));assert.equal(balance(),afterFirst-200000);
 assert.equal((await call('/api/player/games/derby/bet',bet)).status,200);assert.equal(balance(),afterFirst-200000);
 assert.equal(db.prepare('SELECT SUM(cost) n FROM derby_wagers WHERE race_id=? AND employee_id=?').get(race.round,id).n,500000);
 const economy=(await call('/api/player/economy')).data;
 const ticket=await call('/api/player/games/scratch',{tier:'t6',type:'three_match',cost:100000,revision:economy.revision,requestKey:randomUUID()});assert.equal(ticket.status,200,JSON.stringify(ticket.data));
 const stock=db.prepare("SELECT code,price FROM stock_prices WHERE code<>'KARMA' ORDER BY price DESC LIMIT 1").get();
 const trade=await call('/api/player/stocks',{code:stock.code,intent:'open',side:'long',quantity:Math.ceil(600000/stock.price),leverage:3});
 assert.equal(trade.status,200,JSON.stringify(trade.data));
 assert.ok(db.prepare('SELECT margin_used FROM stock_holdings WHERE employee_id=? AND code=?').get(id,stock.code).margin_used>100000);
});
